// Builds: dist/cli.js (Node ESM, undici external), dist/engine.js (Node ESM, for tests),
// dist/web/app.js (browser IIFE), dist/web/index.html + app.css + providers.json.
import { build } from "esbuild";
import fs from "node:fs";
import path from "node:path";

fs.rmSync("dist", { recursive: true, force: true });
fs.mkdirSync("dist/web", { recursive: true });

// 1) the browser bundle first, so the CLI can embed it (the CLI's HTML report and the single-file
//    executables carry the web assets and provider table inside the bundle; no runtime file reads)
await build({ entryPoints: ["web/app.ts"], bundle: true, platform: "browser", format: "iife", target: ["es2020"], outfile: "dist/web/app.js", logLevel: "info" });
fs.mkdirSync("src/generated", { recursive: true });
fs.writeFileSync("src/generated/embedded.ts", `// generated by scripts/build.mjs; do not edit\nexport const APP_JS = ${JSON.stringify(fs.readFileSync("dist/web/app.js", "utf8"))};\nexport const APP_CSS = ${JSON.stringify(fs.readFileSync("web/app.css", "utf8"))};\nexport const PROVIDERS = ${fs.readFileSync("providers.json", "utf8").trim()} as const;\n`);
await build({ entryPoints: ["src/cli.ts"], bundle: true, platform: "node", format: "esm", target: "node20", outfile: "dist/cli.js", external: ["undici"], logLevel: "info" });
await build({ entryPoints: ["src/engine/index.ts"], bundle: true, platform: "node", format: "esm", target: "node20", outfile: "dist/engine.js", logLevel: "info" });
await build({ entryPoints: ["src/forwarder.ts"], bundle: true, platform: "node", format: "esm", target: "node20", outfile: "dist/forwarder.js", external: ["undici"], logLevel: "info" });
for (const f of ["index.html", "app.css", "selftest.html"]) fs.copyFileSync(path.join("web", f), path.join("dist/web", f));
fs.copyFileSync("providers.json", "dist/web/providers.json");
fs.copyFileSync("test/fixtures/sample.har", "dist/web/sample.har");
fs.chmodSync("dist/cli.js", 0o755);
console.log("built dist/");
